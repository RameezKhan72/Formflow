def two_d(kf, start, end, **extra):
    """2D demonstrator / engine keyframes when the 3D pose needs moves the
    sagittal 2D figure cannot show (sideways arms, supported poses)."""
    kf = dict(kf)
    kf["start2d"], kf["end2d"] = start, end
    kf.update(extra)
    return kf


